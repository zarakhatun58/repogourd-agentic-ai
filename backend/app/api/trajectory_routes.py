from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.db.database import get_db
from app.models.analysis import AnalysisRun
from app.models.agent_trajectory import AgentTrajectory


router = APIRouter(
    prefix="/analyses",
    tags=["Analysis Trajectory"],
)


@router.get(
    "/{analysis_id}/trajectory",
    summary="Get analysis agent trajectory",
    description=(
        "Returns the observable execution trajectory for an analysis run. "
        "The trajectory contains workflow events, tool calls, inputs, "
        "outputs, and observations. Hidden chain-of-thought is never stored "
        "or returned."
    ),
)
def get_analysis_trajectory(
    analysis_id: UUID,
    db: Session = Depends(get_db),
):
    """
    Return the observable agent trajectory for an analysis.

    The trajectory represents execution events generated by the
    RepoGuard analysis workflow.

    It does NOT expose hidden chain-of-thought.

    Expected workflow:

        1. Analysis started
        2. Repository inspection started
        3. Repository inspected
        4. Security scan started
        5. Findings generated
        6. Evidence collection started
        7. Evidence collected
        8. Verification started
        9. Verification completed
        10. Analysis completed

    A failed analysis may additionally contain step 999.
    """

    # -------------------------------------------------------------
    # Verify analysis exists
    # -------------------------------------------------------------

    analysis = (
        db.query(AnalysisRun)
        .filter(
            AnalysisRun.id == analysis_id
        )
        .first()
    )

    if not analysis:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Analysis not found",
        )

    # -------------------------------------------------------------
    # Load trajectory
    # -------------------------------------------------------------

    trajectory_rows = (
        db.query(AgentTrajectory)
        .filter(
            AgentTrajectory.analysis_run_id == analysis_id
        )
        .order_by(
            AgentTrajectory.step_number.asc(),
            AgentTrajectory.created_at.asc(),
        )
        .all()
    )

    # -------------------------------------------------------------
    # Convert SQLAlchemy objects into API-safe response objects
    # -------------------------------------------------------------

    trajectory = []

    for item in trajectory_rows:
        trajectory.append(
            {
                "id": str(item.id),
                "analysis_run_id": str(
                    item.analysis_run_id
                ),
                "step_number": item.step_number,
                "event_type": item.event_type,
                "tool_name": item.tool_name,
                "input_data": item.input_data,
                "output_data": item.output_data,
                "observation": item.observation,
                "created_at": (
                    item.created_at.isoformat()
                    if item.created_at
                    else None
                ),
            }
        )

    # -------------------------------------------------------------
    # Return structured trajectory response
    # -------------------------------------------------------------

    return {
        "analysis_id": str(analysis.id),
        "status": analysis.status,
        "agent_type": analysis.agent_type,
        "commit_sha": analysis.commit_sha,
        "trajectory_count": len(trajectory),
        "trajectory": trajectory,
    }